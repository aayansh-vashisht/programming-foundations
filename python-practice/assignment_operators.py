# ASSIGNMENT OPERATORS


# Basic assignment
x = 10

print(x)


# Change a value
x = 10
x = 20

print(x)


# Addition assignment
score = 10
score += 5

print(score)


# Subtraction assignment
money = 100
money -= 30

print(money)


# Multiplication assignment
number = 5
number *= 4

print(number)


# Division assignment
number = 20
number /= 4

print(number)


# Floor division assignment
number = 20
number //= 3

print(number)


# Modulus assignment
number = 17
number %= 5

print(number)


# Power assignment
number = 3
number **= 2

print(number)


# Update many times
score = 10

score += 5
score *= 2
score -= 4

print(score)


# Update price
price = 100

price += 20
price -= 10

print(price)


# User input
balance = 100

deposit = float(input("Enter deposit amount: "))

balance += deposit

print(f"New balance: {balance:.2f}")


# Subtract from balance
withdrawal = float(input("Enter withdrawal amount: "))

balance -= withdrawal

print(f"New balance: {balance:.2f}")


# Counter
count = 0

count += 1
count += 1
count += 1

print(count)


# Compare assignment and comparison
x = 10

print(x)
print(x == 10)
